// Deterministic offline bundle: browser hook + parser + local bridge. No npm/network step.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const vendor=path.join(root,'vendor/protocol');
const target=path.join(root,'ios/AudioLocal/protocol-capture.js');
const names=['hook-capture.js','parse.mjs','bridge.js'];
const bodies=names.map(name=>fs.readFileSync(path.join(vendor,name),'utf8'));
const hashes=bodies.map((body,i)=>`${names[i]} ${crypto.createHash('sha256').update(body).digest('hex')}`);
const parser=bodies[1].replace(/^export\s+/gm,'');
if (/^\s*(?:import|export)\s/m.test(parser)) throw new Error('Unexpected module syntax; do not silently generate a browser-invalid bundle');
let output=`/* GENERATED by tools/build-ios-protocol.mjs. Do not edit directly.\n${hashes.join('\n')}\n */\n(function () {\n'use strict';\nif (typeof window === 'undefined' || window.__houmenProtocol) return;\n${bodies[0]}\nconst capture = window.__shengxunCapture;\nif (!capture) return;\n// Keep the bounded raw response buffer private to this bundle; never export it to Swift.\ntry { delete window.__shengxunCapture; } catch (_) {}\n${parser}\n${bodies[2]}\n})();\n`;
// Git cloud checkout normalizes text resources to LF; emit the same portable bytes.
output=output.replace(/\r\n/g,'\n');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==output) throw new Error('protocol-capture.js is stale; run node tools/build-ios-protocol.mjs');
  console.log('iOS protocol bundle matches vendored sources');
} else {
  fs.mkdirSync(path.dirname(target),{recursive:true});
  if (fs.existsSync(target) && fs.readFileSync(target,'utf8')!==output) {
    const old=fs.readFileSync(target);const hash=crypto.createHash('sha256').update(old).digest('hex');
    const backup=path.join(root,'work/backups/protocol',`protocol-capture-${hash}.js`);
    fs.mkdirSync(path.dirname(backup),{recursive:true});
    if (!fs.existsSync(backup)) fs.writeFileSync(backup,old,{flag:'wx'});
  }
  const temp=target+'.tmp';fs.writeFileSync(temp,output,'utf8');fs.renameSync(temp,target);
  console.log(`Built ${target} (${Buffer.byteLength(output)} bytes)`);
}
